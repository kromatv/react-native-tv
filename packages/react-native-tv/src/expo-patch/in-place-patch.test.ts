import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { testApp, type TestApp } from '../app.fixtures.ts';
import { EXPO_CLI_ENTRY, EXPO_CLI_ENTRY_FILE, installExpoCli } from './expo-cli.fixtures.ts';
import { addExpoCliHook } from './expo-cli-hook.ts';
import { patchExpoCli } from './patch-expo-cli.ts';
import type { RunManager } from './run-manager.ts';

let app: TestApp;

const YARN_1_LOCKFILE = '# THIS IS AN AUTOGENERATED FILE.\n# yarn lockfile v1\n\n\n';

const noManager: RunManager = (command) => {
  throw new Error(`${command} has no patch feature to run`);
};

function postinstall(file = 'package.json'): unknown {
  return JSON.parse(readFileSync(join(app.root, file), 'utf8')).scripts?.postinstall;
}

beforeEach(() => {
  app = testApp();
  installExpoCli(app);
  app.write('package.json', '{\n  "name": "app"\n}\n');
});

afterEach(() => {
  app.remove();
});

describe('patchExpoCli with a package manager that has no patch feature', () => {
  it.each([
    ['package-lock.json', '', 'npm'],
    ['yarn.lock', YARN_1_LOCKFILE, 'yarn-classic'],
  ])(
    'with %s, adds the hook to the installed file and itself to postinstall',
    (lockfile, content, manager) => {
      app.write(lockfile, content);

      expect(patchExpoCli(app.root, noManager)).toEqual({
        state: 'patched',
        version: '58.1.20',
        manager,
        installDir: app.root,
        changed: ['package.json'],
        removed: [],
      });
      expect(readFileSync(join(app.root, EXPO_CLI_ENTRY_FILE), 'utf8')).toBe(
        addExpoCliHook(EXPO_CLI_ENTRY),
      );
      expect(postinstall()).toBe('rn-tv expo-patch');
    },
  );

  it('adds the hook again after an install, with nothing to commit', () => {
    app.write('package-lock.json', '');
    app.write('package.json', { scripts: { postinstall: 'rn-tv expo-patch' } });

    expect(patchExpoCli(app.root, noManager)).toMatchObject({ state: 'patched', changed: [] });
    expect(patchExpoCli(app.root, noManager)).toMatchObject({ state: 'present', changed: [] });
  });

  it('puts postinstall back when the hook is there and the script is not', () => {
    app.write('package-lock.json', '');
    installExpoCli(app, addExpoCliHook(EXPO_CLI_ENTRY));

    expect(patchExpoCli(app.root, noManager)).toMatchObject({
      state: 'present',
      changed: ['package.json'],
    });
    expect(postinstall()).toBe('rn-tv expo-patch');
  });

  it("writes the script in the app's own package.json in a workspace", () => {
    app.write('package-lock.json', '');
    app.write('clients/tv/package.json', { scripts: { postinstall: 'patch-package' } });

    expect(patchExpoCli(join(app.root, 'clients/tv'), noManager)).toMatchObject({
      state: 'patched',
      installDir: app.root,
      changed: [join('clients', 'tv', 'package.json')],
    });
    expect(postinstall('clients/tv/package.json')).toBe('patch-package && rn-tv expo-patch');
    expect(postinstall()).toBeUndefined();
  });

  it('changes nothing in an app whose package.json it cannot read', () => {
    app.write('package-lock.json', '');

    expect(() => patchExpoCli(join(app.root, 'clients/tv'), noManager)).toThrow(
      'is not a package.json rn-tv can read.',
    );
    expect(readFileSync(join(app.root, EXPO_CLI_ENTRY_FILE), 'utf8')).toBe(EXPO_CLI_ENTRY);
  });
});
